/**
 * Colores propios de PetConnect que no forman parte del set base de Material 3
 * (por ejemplo "success" para reservas confirmadas o vacunas al día).
 * Se exponen vía CompositionLocal para poder llamarlos como
 * PetConnectTheme.extraColors.success dentro de cualquier composable.
 */
data class PetConnectExtraColors(
    val success: Color,
    val onSuccess: Color,
    val successContainer: Color,
    val onSuccessContainer: Color,
)

private val LightExtraColors = PetConnectExtraColors(
    success = SuccessLight,
    onSuccess = OnSuccessLight,
    successContainer = SuccessContainerLight,
    onSuccessContainer = OnSuccessContainerLight,
)

private val DarkExtraColors = PetConnectExtraColors(
    success = SuccessDark,
    onSuccess = OnSuccessDark,
    successContainer = SuccessContainerDark,
    onSuccessContainer = OnSuccessContainerDark,
)

val LocalPetConnectExtraColors = staticCompositionLocalOf {
    LightExtraColors
}

@Composable
fun PetConnectTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Deja esto en false si quieres que la marca (teal/coral) se vea igual
    // en todos los dispositivos, en vez de adaptarse al Material You del usuario.
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val extraColors = if (darkTheme) DarkExtraColors else LightExtraColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.primary.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    androidx.compose.runtime.CompositionLocalProvider(
        LocalPetConnectExtraColors provides extraColors
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography, // definido en Type.kt
            content = content
        )
    }
}

/** Acceso rápido: PetConnectTheme.extraColors.success */
object PetConnectTheme {
    val extraColors: PetConnectExtraColors
        @Composable
        get() = LocalPetConnectExtraColors.current
}
